# Installs "start the dashboard with Windows" for the CURRENT user.
#
# No administrator rights are needed: this only writes one file into your own
# Startup folder. It is reversible with uninstall_dashboard_autostart.ps1.
#
# The entry is a tiny .vbs that launches scripts\dashboard_autostart.bat with the
# window hidden (style 0) -- the same approach the previous GLM-Dashboard entry
# used, but pointing at versioned code inside the repo instead of a copy.

$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$bat  = Join-Path $repo 'scripts\dashboard_autostart.bat'
if (-not (Test-Path $bat)) { throw "launcher not found: $bat" }

$startup = [Environment]::GetFolderPath('Startup')
$entry   = Join-Path $startup 'Creality-Dashboard.vbs'

$vbs = @"
' Generated by scripts/install_dashboard_autostart.ps1 -- do not edit by hand.
' Keeps the dashboard up at logon. Remove this file to stop starting it.
Set ws = CreateObject("Wscript.Shell")
ws.Run "cmd /c ""$bat""", 0, False
"@

Set-Content -Path $entry -Value $vbs -Encoding ASCII
Write-Host "installed: $entry"
Write-Host "  -> $bat"
Write-Host "It starts at your next logon. To start it now, run:"
Write-Host "  .venv\Scripts\python.exe scripts\dashboard_supervisor.py --restart"
